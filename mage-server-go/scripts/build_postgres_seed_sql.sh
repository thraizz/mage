#!/bin/bash
#
# Build a PostgreSQL seed SQL file from the Java MAGE H2 database.
#
# Output:
#   mage-server-go/data/cards_seed.postgres.sql
#
# That file is intended to be mounted into the Postgres container at:
#   /docker-entrypoint-initdb.d/data/cards_seed.postgres.sql
# so that a fresh:
#   docker compose down -v && docker compose up -d
# will apply migrations and then seed cards automatically.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

INPUT_H2_SQL="${PROJECT_ROOT}/data/cards.sql"
TMP_PG_SQL="${PROJECT_ROOT}/data/cards.sql.postgres.tmp"
OUTPUT_SEED="${PROJECT_ROOT}/data/cards_seed.postgres.sql"

echo "=== Build Postgres Seed SQL (H2 -> SQL -> Postgres) ==="
echo "Project: $PROJECT_ROOT"
echo ""

echo "Step 1: Export H2 database to SQL (cards.sql)"
"$SCRIPT_DIR/h2_to_sql.sh"
echo ""

if [[ ! -f "$INPUT_H2_SQL" ]]; then
  echo "ERROR: expected H2 export at: $INPUT_H2_SQL" >&2
  exit 1
fi

echo "Step 2: Convert H2 SQL to PostgreSQL SQL"
python3 "$SCRIPT_DIR/convert_h2_to_postgres.py" "$INPUT_H2_SQL" "$TMP_PG_SQL"
echo ""

echo "Step 3: Build seed file: $OUTPUT_SEED"
{
  echo "-- AUTO-GENERATED FILE. DO NOT EDIT."
  echo "-- Generated by: mage-server-go/scripts/build_postgres_seed_sql.sh"
  echo "-- Source: Java MAGE H2 DB -> mage-server-go/data/cards.sql"
  echo ""
  cat "$TMP_PG_SQL"
  echo ""
  echo "-- Indexes for Java-exported tables (performance during migration)"
  echo "CREATE INDEX IF NOT EXISTS idx_card_name ON card(name);"
  echo "CREATE INDEX IF NOT EXISTS idx_card_setcode ON card(setcode);"
  echo "CREATE INDEX IF NOT EXISTS idx_card_classname ON card(classname);"
  echo "CREATE INDEX IF NOT EXISTS idx_card_name_set ON card(name, setcode);"
  echo "CREATE INDEX IF NOT EXISTS idx_card_types ON card(types);"
  echo "CREATE INDEX IF NOT EXISTS idx_card_manavalue ON card(manavalue);"
  echo "ANALYZE card;"
  echo "ANALYZE expansion;"
  echo ""
  echo "-- Migrate data into Go server's cards table (created by migrations)"
  echo "TRUNCATE cards RESTART IDENTITY CASCADE;"
  echo ""
  echo "INSERT INTO cards (card_number, set_code, name, card_type, mana_cost, power, toughness, rules_text, rarity, card_class_name)"
  echo "SELECT"
  echo "    cardnumber,"
  echo "    setcode,"
  echo "    name,"
  echo "    types,"
  echo "    REPLACE(manacosts, '@@@', ''),"
  echo "    power,"
  echo "    toughness,"
  echo "    rules,"
  echo "    rarity,"
  echo "    classname"
  echo "FROM card;"
  echo ""
  echo "ANALYZE cards;"
} > "$OUTPUT_SEED"

rm -f "$TMP_PG_SQL"

echo "✓ Seed SQL ready: $OUTPUT_SEED"
echo ""
echo "Next steps:"
echo "  1) Re-deploy/copy to server so it's available under ~/gomage/mage-server-go/data/"
echo "  2) On server: docker compose down -v && docker compose up -d"
echo ""
