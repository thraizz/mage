func init() {
	cards.Register("Ichormoon Gauntlet", NewIchormoonGauntlet)
}

// NewIchormoonGauntlet creates a Ichormoon Gauntlet
// {2}{U} - ARTIFACT
func NewIchormoonGauntlet(ownerID uuid.UUID, info *cards.CardInfo) (*game.Card, error) {
	card := game.NewCard(ownerID, "Ichormoon Gauntlet")
	card.ManaCost = "{2}{U}"
	card.Types = []string{"ARTIFACT"}
	card.SetCode = "M21"
	card.Rarity = "common"

	ability0, err := abilities.NewSpellAbilityBuilder(card.ID, card.ManaCost).
		// TODO: GainAbilityControlledEffect with complex parameters
		Build()
	if err != nil {
		return nil, err
	}
	card.AddAbility(ability0)
	return card, nil
}
